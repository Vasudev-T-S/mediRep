async def run_mock_pipeline(report_id: str, delay_per_stage: float = 0.2) -> None:
    """Run simulated background processing for a report."""
    async with AsyncSessionLocal() as db:
        stmt = select(Report).where(Report.id == report_id)
        res = await db.execute(stmt)
        report = res.scalar_one_or_none()
        if not report:
            return

        report.status = ReportStatus.processing.value
        await db.commit()

    total_stages = len(STAGE_ORDER)

    for idx, stage in enumerate(STAGE_ORDER[:-1]):
        progress = round((idx + 1) / total_stages, 2)
        async with AsyncSessionLocal() as db:
            stmt = select(Report).where(Report.id == report_id)
            res = await db.execute(stmt)
            report = res.scalar_one_or_none()
            if report:
                report.stage = stage.value
                report.progress = progress
                await db.commit()

        await asyncio.sleep(delay_per_stage)

    # Final completed state
    async with AsyncSessionLocal() as db:
        stmt = select(Report).where(Report.id == report_id)
        res = await db.execute(stmt)
        report = res.scalar_one_or_none()
        if report:
            canned = build_canned_result(report_id, report.report_type)
            report.status = ReportStatus.completed.value
            report.stage = ReportStage.done.value
            report.progress = 1.0
            report.result_json = canned.model_dump_json()
            report.completed_at = datetime.now(timezone.utc)
            await db.commit()
