"""Pydantic v2 models for the AnalysisResult payload (section 7.2 of CONTEXT.md).

These are the canonical data shapes returned by GET /api/reports/{id}/result.
Safety rules (section 9) are enforced in services/safety/ before these are
populated; the models themselves are value objects with no business logic.
"""

from __future__ import annotations

from enum import Enum
from typing import Optional
from uuid import UUID

from pydantic import BaseModel, Field


# ── Enumerations ──────────────────────────────────────────────────────────────


class ReportType(str, Enum):
    """Broad category of the uploaded medical report."""

    lab = "lab"
    pathology = "pathology"
    discharge = "discharge"
    clinical_note = "clinical_note"
    other = "other"


class FindingStatus(str, Enum):
    """Abnormality flag for a lab finding.

    Determined deterministically from reference ranges — never by the LLM.
    """

    low = "low"
    normal = "normal"
    high = "high"
    unknown = "unknown"   # unit mismatch, missing range, or ambiguous value


class AnalysisMode(str, Enum):
    """Processing mode used to produce a report result."""

    mock = "mock"
    entity_extraction = "entity_extraction"


# ── Sub-models ────────────────────────────────────────────────────────────────


class RedFlag(BaseModel):
    """Indicates presence of critical terms (e.g. 'malignant', 'urgent').

    When triggered=True, lifestyle must be empty and the UI shows an urgent
    message prominently (section 4, rule 5 of CONTEXT.md).
    """

    triggered: bool = False
    message: Optional[str] = None


class Finding(BaseModel):
    """A single lab or clinical finding extracted from the report."""

    name: str = Field(..., description="Test or measurement name, e.g. 'Hemoglobin'")
    value: Optional[float] = Field(None, description="Numeric value if parseable")
    unit: Optional[str] = Field(None, description="Unit string, e.g. 'g/dL'")
    reference_range: Optional[str] = Field(
        None, description="Range string as printed in report or from reference table"
    )
    status: FindingStatus = FindingStatus.unknown
    explanation: str = Field(
        ..., description="Plain-language explanation generated by the LLM"
    )


class KBSource(BaseModel):
    """A knowledge-base document cited in lifestyle advice or term explanations."""

    id: str = Field(..., description="Internal KB chunk ID, e.g. 'kb_012'")
    title: str
    url: str


class MedicalTerm(BaseModel):
    """A medical term detected in the report, with plain-language explanation."""

    term: str
    explanation: str
    source_ids: list[str] = Field(
        default_factory=list,
        description="KB chunk IDs that ground this explanation",
    )


class DetectedEntity(BaseModel):
    """A medical entity recognized by the named-entity model."""

    text: str
    label: str
    confidence: float = Field(..., ge=0.0, le=1.0)
    start: Optional[int] = Field(None, ge=0)
    end: Optional[int] = Field(None, ge=0)


class Lifestyle(BaseModel):
    """General, evidence-grounded lifestyle suggestions.

    Must be empty (all lists empty, sources empty) when red_flag.triggered is True.
    Every item must trace to a source in `sources`; otherwise it is dropped by the
    safety layer before this object is populated.
    """

    diet: list[str] = Field(default_factory=list)
    physical_activity: list[str] = Field(default_factory=list)
    precautions: list[str] = Field(default_factory=list)
    sources: list[KBSource] = Field(default_factory=list)


class Meta(BaseModel):
    """Pipeline metadata attached to every result for transparency."""

    model: str = Field(..., description="LLM model identifier used")
    pipeline_version: str = Field(..., description="Semver of the pipeline code")
    processing_seconds: float = Field(..., ge=0)
    readability_grade: Optional[float] = Field(
        None, description="Flesch-Kincaid grade level of overall_summary"
    )
    warnings: list[str] = Field(
        default_factory=list,
        description="Non-fatal issues logged by safety layer (faithfulness violations, etc.)",
    )


# ── Root result ───────────────────────────────────────────────────────────────


class AnalysisResult(BaseModel):
    """Top-level payload returned by GET /api/reports/{id}/result.

    This is the canonical cross-track contract (section 7.2 of CONTEXT.md).
    """

    report_id: UUID
    report_type: ReportType
    analysis_mode: AnalysisMode = AnalysisMode.mock
    overall_summary: str = Field(
        ..., description="Plain-language summary at ~6th-8th grade reading level"
    )
    red_flag: RedFlag = Field(default_factory=RedFlag)
    key_findings: list[Finding] = Field(default_factory=list)
    medical_terms: list[MedicalTerm] = Field(default_factory=list)
    detected_entities: list[DetectedEntity] = Field(default_factory=list)
    lifestyle: Lifestyle = Field(default_factory=Lifestyle)
    questions_for_doctor: list[str] = Field(default_factory=list)
    disclaimer: str = Field(
        ...,
        description=(
            "Persistent safety disclaimer shown on every results page. "
            "Injected by services/safety/disclaimer.py."
        ),
    )
    meta: Meta
